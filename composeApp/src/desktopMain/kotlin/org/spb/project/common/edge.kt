package org.spb.project.common

/**
 * Ребро в неориентированном или ориентированном графе.
 *
 * @property vertex индекс конечной вершины, к которой ведёт это ребро
 * @property weight числовой вес ребра — может служить для оценки «стоимости» или «расстояния»
 * @property color цвет ребра в формате ARGB (Int), используется при визуализации
 */
open class Edge(
    var vertex: Int,    // куда идёт ребро (индекс вершины в списке)
    var weight: Int,    // вес или длина ребра
    var color: Int      // цвет, в котором ребро будет нарисовано
)